"""Generate sim/src/x86_trig_consts.h from data.bin written by dump_x86_libm.c (x86_64 libm sinf's
constant area, starting at sinf+0x45b00). Offsets are from the disassembly of sinf/cosf."""
import struct, sys
d = open(sys.argv[1] if len(sys.argv) > 1 else "data.bin", "rb").read()
B = 0x45b00
q = lambda o: struct.unpack("<Q", d[o - B:o - B + 8])[0]
T = [q(0x463f0 + 8 * i) for i in range(10)]
n = (0x3e800000 >> 24) + 1
tbl = [(q(0x46000 + 16 * i), q(0x46000 + 16 * i + 8)) for i in range(n)]
L = ["// generated by sim/tools/libm/gen_consts.py from the x86_64 macOS libsystem_m sinf/cosf (read at",
     "// runtime from an x86_64 process under Rosetta): polynomial, 2/pi, and the per-exponent reduction table",
     f"static const uint64_t X86_TWO_OVER_PI = 0x{q(0x45fd0):016x}ULL;",
     "static const uint64_t X86_POLY[10] = {" + ", ".join(f"0x{t:016x}ULL" for t in T) + "};",
     f"static const uint64_t X86_REDUCE[{n}][2] = {{"]
L += [f"  {{0x{a:016x}ULL, 0x{b:016x}ULL}}," for a, b in tbl] + ["};"]
open(sys.argv[2] if len(sys.argv) > 2 else "../../src/x86_trig_consts.h", "w").write("\n".join(L) + "\n")
