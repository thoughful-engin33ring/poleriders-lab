#!/usr/bin/env python3
"""Generate src/game/assets.h: every PoleRiders constant listed in re_notes/globals.md (Assets
constants, class statics, level statics), with the exact bytes read from the game binary (floats as
hex-float literals, so nothing is lost to decimal printing).

    gen_assets.py [out.h]"""
import os, re, struct, sys

SIM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BIN = os.path.expanduser("~/Library/Application Support/Steam/steamapps/common/Sportsfriends/"
                         "Sportsfriends.app/Contents/MacOS/Sportsfriends.orig")
ROW = re.compile(r"^\|\s*(0x[0-9a-f]+)\s*\|\s*`([^`]+)`\s*\|\s*([^|]*)\|")


def main(dst):
    b = open(BIN, "rb").read()
    md = open(os.path.join(SIM, "re_notes", "globals.md")).read()
    sec = md[md.index("## 2."):md.index("## 4.")]
    groups = {}
    for ln in sec.split("\n"):
        m = ROW.match(ln)
        if not m:
            continue
        addr, sym, val = int(m.group(1), 16), m.group(2).strip(), m.group(3).strip()
        if sym.endswith("]") or "(" in sym:
            continue
        raw = b[addr - 0x100000000: addr - 0x100000000 + 4]
        i, f = struct.unpack("<i", raw)[0], struct.unpack("<f", raw)[0]
        is_int = sym.startswith(("BODY_", "FIXTURE_", "HANDLE_")) or "(int)" in val or (0 <= i < 1 << 20 and i != 0 and abs(f) < 1e-30)
        ns, name = (sym.split("::", 1) if "::" in sym else ("Assets", sym))
        groups.setdefault(ns, []).append((name, addr, i if is_int else f, is_int, val))
    out = ["// generated by sim/tools/gen_assets.py from re_notes/globals.md + the game binary — do not edit",
           "// Exact values of the game's constants (PoleRiders::Assets, class statics, level statics).",
           "// Userdata tags are `static const int` objects: the game stores their ADDRESSES in b2 userData.",
           "#pragma once", "", "namespace PoleRiders {"]
    for ns, rows in groups.items():
        out.append(f"namespace {ns}_ {{" if ns != "Assets" else "namespace Assets {")
        if ns == "Assets":  # BODY_PLAYER1..4 @0x10028e06c..78: contiguous, indexed by player number
            out.append("inline const int BODY_PLAYER[4] = {0, 1, 2, 3};  // @0x10028e06c (BODY_PLAYER1..4)")
        for name, addr, v, is_int, note in rows:
            if is_int:
                out.append(f"inline const int {name} = {v};  // @{addr:#x}")
            else:
                out.append(f"inline const float {name} = {float(v).hex()}f;  // @{addr:#x} = {v!r}")
        out.append("}" + f"  // namespace {ns}")
    out.append("}  // namespace PoleRiders")
    open(dst, "w").write("\n".join(out) + "\n")
    print(dst, {k: len(v) for k, v in groups.items()})


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(SIM, "src", "game", "assets.h"))
